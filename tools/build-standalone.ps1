# Regenerate the self-contained Moodle distribution from the maintainable source files.
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$indexPath = Join-Path $projectRoot 'index.html'
$cssPath = Join-Path $projectRoot 'css\style.css'
$jsPath = Join-Path $projectRoot 'js\app.js'
$outputDirectory = Join-Path $projectRoot 'standalone'
$outputPath = Join-Path $outputDirectory 'sampling-distributions.html'
$utf8NoBom = [Text.UTF8Encoding]::new($false)

foreach ($requiredPath in @($indexPath, $cssPath, $jsPath)) {
    if (-not (Test-Path -LiteralPath $requiredPath -PathType Leaf)) {
        throw "Required source file not found: $requiredPath"
    }
}

$html = [IO.File]::ReadAllText($indexPath)
$css = [IO.File]::ReadAllText($cssPath).TrimEnd()
$javascript = [IO.File]::ReadAllText($jsPath).TrimEnd()
$styleMarker = '<link rel="stylesheet" href="css/style.css">'
$scriptMarker = '<script src="js/app.js"></script>'

if (-not $html.Contains($styleMarker) -or -not $html.Contains($scriptMarker)) {
    throw 'index.html does not contain the expected relative CSS and JavaScript references.'
}

$standalone = $html.Replace($styleMarker, "<style>`r`n$css`r`n  </style>")
$standalone = $standalone.Replace($scriptMarker, "<script>`r`n$javascript`r`n  </script>")
$standalone = $standalone.Replace('<!doctype html>', "<!doctype html>`r`n<!-- Generated from index.html, css/style.css, and js/app.js. Do not edit this file directly. -->")

[IO.Directory]::CreateDirectory($outputDirectory) | Out-Null
[IO.File]::WriteAllText($outputPath, $standalone, $utf8NoBom)
Write-Host "Generated $outputPath"
